export function applyChromeOverlay(locale: Locale, t: Translations): Translations {
  if (locale === "en" || locale === "kr") return t;
  const chrome = CHROME[locale];
  if (!chrome) return t;
  return {
    ...t,
    nav: chrome.nav,
    hero: chrome.hero,
    footer: chrome.footer,
    credits: chrome.credits,
  };
}
